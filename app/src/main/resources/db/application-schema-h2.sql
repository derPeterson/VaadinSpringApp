-- Aktuelles H2-Anwendungsschema. Tabellen werden angelegt, nicht nachträglich umgebaut.

CREATE TABLE IF NOT EXISTS admin_notification_attempt (
    completed_at timestamp(6),
    id bigint generated by default as identity,
    queue_id bigint not null,
    started_at timestamp(6) not null,
    status enum ('IN_PROGRESS','NOT_SENT','SENT','UNKNOWN') not null,
    primary key (id),
    constraint uk_admin_attempt_queue unique (queue_id)
);

CREATE TABLE IF NOT EXISTS config (
    id bigint generated by default as identity,
    config_key varchar(255) not null unique,
    config_value varchar(255) not null,
    primary key (id)
);

CREATE TABLE IF NOT EXISTS external_providers (
    provider varchar(16) not null primary key,
    client_id varchar(512) not null,
    encrypted_client_secret varchar(12000) not null,
    enabled boolean not null,
    version bigint not null
);

CREATE TABLE IF NOT EXISTS login_attempt_guard (
    id integer not null,
    primary key (id)
);

CREATE TABLE IF NOT EXISTS login_attempts (
    failures integer not null,
    blocked_until timestamp(6) with time zone,
    last_activity timestamp(6) with time zone not null,
    window_started_at timestamp(6) with time zone not null,
    identity_hash varchar(64) not null,
    primary key (identity_hash)
);

CREATE TABLE IF NOT EXISTS roles (
    id bigint generated by default as identity,
    name enum ('ROLE_ADMIN','ROLE_GUEST','ROLE_SUPERADMIN','ROLE_USER') not null unique,
    primary key (id)
);

CREATE TABLE IF NOT EXISTS users (
    birth_date date,
    enabled boolean not null,
    status_manually_set boolean not null,
    verification_pending boolean not null,
    id bigint generated by default as identity,
    last_activity timestamp(6) with time zone not null,
    version bigint not null,
    email varchar(255) not null,
    first_name varchar(255) not null,
    last_name varchar(255) not null,
    password varchar(255),
    access_version varchar(36) default random_uuid() not null,
    preferred_locale varchar(255) not null,
    gender enum ('FEMALE','MALE','OTHER'),
    status enum ('ABSENT','AVAILABLE','EMPLOYED','OFFLINE') not null,
    primary key (id),
    constraint uk_users_email unique (email),
    constraint ck_users_canonical_email check (email = lower(trim(email)) and length(email) > 0 and ascii(left(email, 1)) > 32 and ascii(right(email, 1)) > 32)
);

CREATE TABLE IF NOT EXISTS external_identities (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    provider varchar(16) not null,
    issuer varchar(255) not null,
    subject varchar(255) not null,
    constraint fk_external_user foreign key (user_id) references users(id) on delete cascade,
    constraint uk_external_subject unique (provider, issuer, subject),
    constraint uk_external_user_provider unique (user_id, provider)
);

CREATE TABLE IF NOT EXISTS two_factor_accounts (
    user_id bigint not null primary key,
    version bigint not null,
    revision uuid not null,
    encrypted_secret varchar(512),
    previously_enrolled boolean not null,
    operator_enrollment boolean not null,
    enrolled_at timestamp(6) with time zone,
    accepted_step bigint not null,
    failed_attempts integer not null,
    attempt_window timestamp(6) with time zone,
    blocked_until timestamp(6) with time zone,
    constraint fk_two_factor_account foreign key (user_id) references users(id) on delete cascade,
    constraint ck_two_factor_attempts check (failed_attempts >= 0 and accepted_step >= -1),
    constraint ck_two_factor_enrolled check (encrypted_secret is null or (previously_enrolled and enrolled_at is not null))
);

CREATE TABLE IF NOT EXISTS two_factor_policy (
    id integer not null primary key,
    version bigint not null,
    rules varchar(12000) not null,
    constraint ck_two_factor_policy_singleton check (id = 1)
);

CREATE TABLE IF NOT EXISTS two_factor_recovery_codes (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    digest varchar(64) not null,
    used_at timestamp(6) with time zone,
    constraint fk_two_factor_recovery foreign key (user_id) references users(id) on delete cascade,
    constraint uk_two_factor_recovery unique (user_id, digest)
);

CREATE TABLE IF NOT EXISTS two_factor_challenges (
    id uuid not null primary key,
    version bigint not null,
    user_id bigint not null,
    session_digest varchar(64) not null,
    access_version varchar(36) not null,
    factor_revision uuid not null,
    policy_revision bigint not null,
    action enum ('LOGIN','ADMINISTRATION','PASSWORD','EMAIL','LINK_PROVIDER','UNLINK_PROVIDER','MANAGE_FACTOR','MANAGE_RECOVERY_CODES','SECURITY_CONFIGURATION') not null,
    kind enum ('ACTION','ENROLLMENT','GOOGLE_EMAIL','RECOVERY_OUTPUT') not null,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    consumed boolean not null,
    attempts integer not null,
    encrypted_payload varchar(8192),
    verification_digest varchar(64),
    contact_address varchar(255),
    operator_enrollment boolean not null,
    setup_proof enum ('PASSWORD','MICROSOFT','GOOGLE_EMAIL','OPERATOR','FACTOR','RECOVERY_CODE'),
    constraint fk_two_factor_challenge foreign key (user_id) references users(id) on delete cascade
);
CREATE INDEX IF NOT EXISTS ix_two_factor_challenges_owner on two_factor_challenges(user_id, session_digest, kind, action);

CREATE TABLE IF NOT EXISTS email_change_token (
    created_at timestamp(6) not null,
    expiry_date timestamp(6) not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    credential_digest varchar(64) not null,
    digest varchar(64) not null unique,
    new_email varchar(255) not null,
    old_email varchar(255) not null,
    status enum ('ACTIVE','EXPIRED','INACTIVE','USED') not null,
    primary key (id),
    constraint FKe2qhr7cd0lvfqtlw15b5dt8fj foreign key (user_id) references users on delete cascade
);

CREATE TABLE IF NOT EXISTS email_queue (
    retry_count integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    last_retry_at timestamp(6),
    user_id bigint not null,
    recipient varchar(255),
    subject varchar(255) not null,
    body CLOB not null,
    email_type enum ('NOTIFICATION','PASSWORD_RESET','PROMOTION','VERIFICATION') not null,
    status enum ('FAILED','IN_PROGRESS','PENDING','SENT') not null,
    primary key (id),
    constraint FKg4sjtmlodntoq4mkn92wyg3bo foreign key (user_id) references users on delete cascade
);

CREATE TABLE IF NOT EXISTS password_reset_token (
    expiry_date timestamp(6) not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    token varchar(255) not null unique,
    status enum ('ACTIVE','EXPIRED','INACTIVE','USED') not null,
    primary key (id),
    constraint FK83nsrttkwkb6ym0anu051mtxn foreign key (user_id) references users on delete cascade
);

CREATE TABLE IF NOT EXISTS user_avatar (
    has_image boolean not null,
    user_id bigint not null,
    version bigint not null,
    image_revision uuid,
    image_data blob,
    uploaded_at timestamp(6) with time zone,
    original_format enum ('JPEG','PNG'),
    original_size_bytes bigint,
    original_width integer,
    original_height integer,
    mode enum ('CUSTOM','INITIALS') not null,
    primary key (user_id),
    constraint FKlatwcvwggmxieyymk3e3aah09 foreign key (user_id) references users on delete cascade,
    constraint ck_user_avatar_image_metadata check (
        (not has_image and image_data is null and image_revision is null
            and uploaded_at is null and original_format is null
            and original_size_bytes is null and original_width is null and original_height is null)
        or
        (has_image and image_data is not null and image_revision is not null
            and uploaded_at is not null and original_format is not null
            and original_size_bytes is not null and original_size_bytes > 0
            and original_width is not null and original_width > 0
            and original_height is not null and original_height > 0)
    )
);

CREATE TABLE IF NOT EXISTS user_notifications (
    broadcast boolean not null,
    recipient_count integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    sender_id bigint,
    request_key varchar(80) not null,
    title varchar(120),
    body varchar(4000),
    type enum ('ADMIN_ANNOUNCEMENT','EMAIL_CHANGED','PASSWORD_CHANGED','PASSWORD_RESET','ROLES_CHANGED','RECOVERY_REQUEST','SUPPORT_REPLY','SUPPORT_REQUESTER_CLOSED') not null,
    support_ticket_number varchar(24),
    support_reply_id bigint,
    support_ticket_version bigint,
    primary key (id),
    constraint uk_user_notification_request unique (request_key),
    constraint FKcfgxwytt007vbi1rf5e6hi7cy foreign key (sender_id) references users on delete set null
);

CREATE TABLE IF NOT EXISTS users_roles (
    role_id bigint not null,
    user_id bigint not null,
    constraint FKj6m8fwv7oqv74fcehir1a9ffy foreign key (role_id) references roles,
    constraint FK2o0jvgh89lemvvo17cbqvdxaa foreign key (user_id) references users
);

CREATE TABLE IF NOT EXISTS verification_token (
    expiry_date timestamp(6) not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    token varchar(255) not null unique,
    status enum ('ACTIVE','EXPIRED','INACTIVE','USED') not null,
    primary key (id),
    constraint FK3asw9wnv76uxu3kr1ekq4i1ld foreign key (user_id) references users on delete cascade
);

CREATE TABLE IF NOT EXISTS user_notification_recipients (
    relevance enum ('ACTIVE','TICKET_ASSIGNED','REQUESTER_CLOSED','TICKET_CLOSED') not null,
    dismissed_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    notification_id bigint not null,
    read_at timestamp(6) with time zone,
    user_id bigint not null,
    primary key (id),
    constraint uk_user_notification_recipient unique (notification_id, user_id),
    constraint FK6kcnuo5jm33u7g26u615im996 foreign key (notification_id) references user_notifications on delete cascade,
    constraint FKhev87gjyjhr4guvvxxw5c1b3p foreign key (user_id) references users on delete cascade
);

CREATE INDEX IF NOT EXISTS idx_email_change_expiry on email_change_token (expiry_date);

CREATE INDEX IF NOT EXISTS idx_login_attempt_activity on login_attempts (last_activity);

CREATE INDEX IF NOT EXISTS idx_user_notification_inbox on user_notification_recipients (user_id, read_at, id);

CREATE INDEX IF NOT EXISTS idx_user_notification_created on user_notifications (created_at);

CREATE INDEX IF NOT EXISTS idx_user_lastactivity_status on users (last_activity, status);

create table if not exists support_tickets (
 id bigint generated by default as identity primary key,
 version bigint not null,
 owner_id bigint not null references users(id) on delete cascade,
 assignee_id bigint references users(id) on delete set null,
 type enum ('RECOVERY') not null,
 status enum ('OPEN','IN_PROGRESS','CLOSED','CLOSED_BY_REQUESTER') not null,
 subject varchar(120) not null,
 created_at timestamp(6) with time zone not null,
 updated_at timestamp(6) with time zone not null,
 public_updated_at timestamp(6) with time zone not null,
 instruction_sent_at timestamp(6) with time zone
);
create index if not exists idx_support_owner on support_tickets(owner_id, public_updated_at);
create table if not exists support_replies (
 id bigint generated by default as identity primary key,
 ticket_id bigint not null references support_tickets(id) on delete cascade,
 author_id bigint references users(id) on delete set null,
 support_author boolean not null,
 kind enum ('MESSAGE','RECOVERY_INSTRUCTIONS') not null,
 body varchar(2000) not null,
 internal boolean not null,
 created_at timestamp(6) with time zone not null
);
create index if not exists idx_support_reply_ticket on support_replies(ticket_id, created_at);

create table if not exists support_ticket_viewers (
 id bigint generated by default as identity primary key,
 ticket_id bigint not null references support_tickets(id) on delete cascade,
 user_id bigint not null references users(id) on delete cascade,
 requester_read_through bigint not null,
 admin_read_through bigint not null,
 subscribed boolean not null,
 constraint uk_support_ticket_viewer unique (ticket_id, user_id)
);
