package de.derpeterson.app.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.ArgumentMatchers.startsWith;
import static org.mockito.Mockito.spy;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;

import de.derpeterson.app.config.RoleSchemaUpdater;
import de.derpeterson.app.model.RoleEntity;
import de.derpeterson.app.model.enums.RoleType;
import jakarta.persistence.EntityManager;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.orm.jpa.LocalContainerEntityManagerFactoryBean;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;

/** Simulates the previous two-role schema in a fresh in-memory DB, never application data. */
class RoleSchemaUpgradeTest {
  @Test
  void schemaUpdateAcceptsNewRolesWithoutReplacingExistingRoleRows() {
    DriverManagerDataSource source =
        new DriverManagerDataSource("jdbc:h2:mem:role-upgrade-" + UUID.randomUUID(), "sa", "");
    LocalContainerEntityManagerFactoryBean factory = new LocalContainerEntityManagerFactoryBean();
    try (var _ = source.getConnection()) {
      JdbcTemplate jdbc = spy(new JdbcTemplate(source));
      jdbc.execute(
          "create table roles (id bigint generated by default as identity primary key, "
              + "name enum ('ROLE_ADMIN', 'ROLE_USER') not null unique)");
      jdbc.update("insert into roles (id, name) values (101, 'ROLE_ADMIN'), (102, 'ROLE_USER')");
      jdbc.execute(
          "create table legacy_role_links (user_id bigint primary key, role_id bigint references roles(id))");
      jdbc.update("insert into legacy_role_links values (201, 101)");
      factory.setDataSource(source);
      factory.setPackagesToScan("de.derpeterson.app.model");
      factory.setJpaVendorAdapter(new HibernateJpaVendorAdapter());
      factory.setJpaPropertyMap(Map.of("hibernate.hbm2ddl.auto", "update"));
      factory.afterPropertiesSet();
      RoleSchemaUpdater updater = new RoleSchemaUpdater(jdbc);
      updater.updateRoleColumn();
      updater.updateRoleColumn();
      verify(jdbc, times(1)).execute(startsWith("alter table roles"));
      try (EntityManager manager = factory.getObject().createEntityManager()) {
        manager.getTransaction().begin();
        manager.persist(RoleEntity.builder().name(RoleType.ROLE_SUPERADMIN).build());
        manager.persist(RoleEntity.builder().name(RoleType.ROLE_GUEST).build());
        manager.getTransaction().commit();
      }
      assertEquals(4, jdbc.queryForObject("select count(*) from roles", Integer.class));
      assertEquals(
          "ROLE_ADMIN", jdbc.queryForObject("select name from roles where id = 101", String.class));
      assertEquals(
          "ROLE_USER", jdbc.queryForObject("select name from roles where id = 102", String.class));
      assertEquals(
          101L,
          jdbc.queryForObject(
              "select role_id from legacy_role_links where user_id = 201", Long.class));
      assertThrows(
          org.springframework.dao.DataIntegrityViolationException.class,
          () -> jdbc.update("insert into legacy_role_links values (202, 999)"));
    } catch (java.sql.SQLException exception) {
      throw new AssertionError(exception);
    } finally {
      if (factory.getObject() != null) {
        factory.destroy();
      }
    }
  }
}
