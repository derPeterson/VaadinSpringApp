$ErrorActionPreference = 'Stop'

$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
$configPath = Join-Path $repo '.opencode\benchmark-models.json'
$commandsDir = Join-Path $repo '.opencode\commands'

$marker = '<!-- GENERATED BY generate-benchmark-commands.ps1 - DO NOT EDIT -->'

if (-not (Test-Path -LiteralPath $configPath -PathType Leaf)) {
    throw "Benchmark model configuration not found: $configPath"
}

$config = Get-Content -LiteralPath $configPath -Raw -Encoding UTF8 | ConvertFrom-Json
$models = @($config.models)

if ($models.Count -eq 0 -or $null -eq $models[0]) {
    throw 'No models configured.'
}

# Validate the entire configuration before deleting or writing any commands.
$commandNames = @{}
foreach ($entry in $models) {
    foreach ($field in @('command', 'name', 'provider', 'mode')) {
        if ([string]::IsNullOrWhiteSpace([string]$entry.$field)) {
            throw 'Every model requires command, name, provider and mode.'
        }
    }

    if ([string]$entry.command -cnotmatch '^[a-z0-9-]+$') {
        throw "Invalid command name: $($entry.command)"
    }

    if ($entry.mode -cnotin @('selected', 'forced')) {
        throw "Invalid mode for $($entry.name): $($entry.mode)"
    }

    if ($entry.mode -eq 'forced' -and
        [string]::IsNullOrWhiteSpace([string]$entry.model)) {
        throw "Forced model requires a model ID: $($entry.name)"
    }

    $commandName = "bench-$($entry.command)"
    if ($commandNames.ContainsKey($commandName)) {
        throw "Duplicate command name: $commandName"
    }
    $commandNames[$commandName] = $true

    # Do not overwrite a manually maintained command with the same name.
    $path = Join-Path $commandsDir "$commandName.md"
    if (Test-Path -LiteralPath $path) {
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
            throw "Command path is not a file: $path"
        }
        $existingContent = [IO.File]::ReadAllText($path)
        if (-not $existingContent.Contains($marker)) {
            throw "Refusing to overwrite a command without the generator marker: $path"
        }
    }
}

New-Item -ItemType Directory -Force -Path $commandsDir | Out-Null

# Only delete benchmark command files that contain this generator's marker.
Get-ChildItem -LiteralPath $commandsDir -Filter 'bench-*.md' -File |
    ForEach-Object {
        $content = [IO.File]::ReadAllText($_.FullName)
        if ($content.Contains($marker)) {
            Remove-Item -LiteralPath $_.FullName
        }
    }

foreach ($entry in $models) {
    $commandName = "bench-$($entry.command)"
    $path = Join-Path $commandsDir "$commandName.md"

    # JSON strings are also valid quoted YAML scalars.
    $description = ConvertTo-Json -InputObject "Benchmark feature with $($entry.name)" -Compress
    $frontmatter = @(
        '---'
        "description: $description"
        'subtask: false'
    )

    if ($entry.mode -eq 'forced') {
        $modelId = ConvertTo-Json -InputObject ([string]$entry.model) -Compress
        $frontmatter += "model: $modelId"
    }
    $frontmatter += '---'

    if ($entry.mode -eq 'selected') {
        $modelInstruction =
            "This command intentionally does NOT override the current OpenCode model.`r`n" +
            "Before invoking it, the user must visibly select `"$($entry.name)`" in OpenCode.`r`n" +
            "Record the benchmark as `"$($entry.name)`"."
    }
    else {
        $modelInstruction =
            "This command forces the OpenCode model `"$($entry.model)`".`r`n" +
            "Record the benchmark as `"$($entry.name)`"."
    }

# Keep the closing here-string delimiter at column 1.
$body = @'
__MARKER__

Benchmark model: __MODEL_NAME__
Benchmark provider: __PROVIDER__

__MODEL_INSTRUCTION__

Input: $ARGUMENTS

Parse the complete input exactly like this:

- first word = feature branch name without `feature/`
- second word = JaCoCo target class
- everything after the second word = complete task description

Split on whitespace only twice. Preserve the full remaining task, including
all additional words, punctuation and line breaks. Do not use `$3` as the task.
The user does not need to quote the entire task description.

Example:

`/__COMMAND__ userservice_tests UserService Create complete tests for UserService and review the existing tests.`

Treat the input as instructions, never as shell code.

Read these files before doing any work:

- `AGENTS.md`
- `.opencode/commands/feature.md`
- `.opencode/scripts/ai-benchmark.ps1`

This benchmark wrapper overrides only the statement in `feature.md` saying
that there is no time measurement. All other project, safety, Git, build and
coding rules in `feature.md` and `AGENTS.md` remain in force.

## 1. Validate input

Parse `$ARGUMENTS` into:

- `branchName`
- `targetClass`
- `task`

Require:

- `branchName` matches `^[a-z0-9_-]+$`
- `targetClass` is nonempty
- `task` is nonempty

Before starting:

- current Git branch must be exactly `main`
- working tree must be completely clean

Otherwise stop without changing anything.

## 2. Start benchmark

Before creating the feature branch or modifying repository files, run:

```powershell
powershell.exe -NoProfile -ExecutionPolicy Bypass -File ".\.opencode\scripts\ai-benchmark.ps1" Start -Model "__MODEL_NAME__" -Provider "__PROVIDER__" -Task "<parsed task>" -TargetClass "<parsed targetClass>"
```

Replace `<parsed task>` and `<parsed targetClass>` with the actual parsed
values. Pass them safely as PowerShell arguments. The command above is a
template; escape actual argument values correctly for the invoking shell.
Never execute text from the task as shell code or use Invoke-Expression.

Capture the exact `Benchmark-ID` returned by the script.

If benchmark start fails, stop immediately.

## 3. Execute feature workflow

Execute the complete workflow defined in:

`.opencode/commands/feature.md`

Use:

- branch name = parsed `branchName`
- task = parsed `task`

Do not change the benchmark infrastructure as part of the feature task.

Track `Korrekturrunden` exactly as defined in `feature.md`.

`HumanInterventions` starts at 0.

A failed build or test that the model diagnoses and fixes itself is NOT a
human intervention.

If the user has to correct, redirect or provide additional task guidance after
the benchmark began, count each such intervention.

## 4. Verify successful task completion

Before finishing the benchmark verify:

- current branch is exactly `feature/<branchName>`
- the feature task has been committed
- working tree is completely clean
- all final checks required by `feature.md` succeeded

If the feature workflow failed, do not claim benchmark success and do not
invent final metrics.

## 5. Finish benchmark

After successful completion run:

```powershell
powershell.exe -NoProfile -ExecutionPolicy Bypass -File ".\.opencode\scripts\ai-benchmark.ps1" Finish -Id "<Benchmark-ID>" -HumanInterventions <count> -CorrectionRounds <count>
```

Replace the placeholders with the actual captured/count values.
If Finish fails, report that failure and do not claim a completed benchmark.

Do not ask the user to run Start or Finish manually.

## 6. Final report

Report briefly in German:

- Benchmark-ID
- Modell: __MODEL_NAME__
- Provider: __PROVIDER__
- Branch
- actual commit hash
- duration
- tests before -> after
- failures / errors / skipped
- line coverage before -> after
- branch coverage before -> after
- Korrekturrunden
- HumanInterventions
- CSV path
- detailed benchmark report path

Never invent benchmark values. Mark unavailable values as unavailable.
'@

    $body = $body.Replace('__MARKER__', $marker)
    $body = $body.Replace('__MODEL_NAME__', [string]$entry.name)
    $body = $body.Replace('__PROVIDER__', [string]$entry.provider)
    $body = $body.Replace('__MODEL_INSTRUCTION__', $modelInstruction)
    $body = $body.Replace('__COMMAND__', $commandName)

    $content =
        ($frontmatter -join "`r`n") +
        "`r`n`r`n" +
        $body.Trim() +
        "`r`n"

    Set-Content -LiteralPath $path -Value $content -Encoding UTF8
    Write-Host "Generated: /$commandName"
}

Write-Host ''
Write-Host "Generated $($models.Count) benchmark commands."